class GameplayScreen(QWidget):
    def __init__(self):
        super().__init__()
        self.setObjectName("gameplay")
        outer = QVBoxLayout(self)
        outer.setContentsMargins(24, 22, 24, 22)
        heading, detail = title("Adventure", "The road continues with your next choice.")
        outer.addWidget(heading)
        outer.addWidget(detail)
        columns = QHBoxLayout()
        story_column = QVBoxLayout()
        story_column.addWidget(QLabel("Story so far"))
        self.history = QPlainTextEdit()
        self.history.setObjectName("narrationHistory")
        self.history.setReadOnly(True)
        story_column.addWidget(self.history, 1)
        story_column.addWidget(QLabel("Your action"))
        self.action = QPlainTextEdit()
        self.action.setObjectName("playerAction")
        self.action.setMaximumHeight(85)
        self.action.setPlaceholderText("What do you do?")
        story_column.addWidget(self.action)
        self.send_button = QPushButton("Take Action")
        self.send_button.setObjectName("sendActionButton")
        story_column.addWidget(self.send_button, alignment=Qt.AlignmentFlag.AlignRight)
        columns.addLayout(story_column, 3)
        sidebar = QVBoxLayout()
        character_box = QGroupBox("Character")
        character_layout = QVBoxLayout(character_box)
        self.character_name = QLabel()
        self.character_details = QLabel()
        self.character_name.setTextFormat(Qt.TextFormat.PlainText)
        self.character_details.setTextFormat(Qt.TextFormat.PlainText)
        self.character_details.setWordWrap(True)
        character_layout.addWidget(self.character_name)
        character_layout.addWidget(self.character_details)
        sidebar.addWidget(character_box)
        location_box = QGroupBox("Location")
        location_layout = QVBoxLayout(location_box)
        self.location = QLabel()
        self.location.setTextFormat(Qt.TextFormat.PlainText)
        self.location.setWordWrap(True)
        location_layout.addWidget(self.location)
        sidebar.addWidget(location_box)
        inventory_box = QGroupBox("Inventory")
        inventory_layout = QVBoxLayout(inventory_box)
        self.inventory = QListWidget()
        inventory_layout.addWidget(self.inventory)
        sidebar.addWidget(inventory_box, 1)
        quests_box = QGroupBox("Quests")
        quests_layout = QVBoxLayout(quests_box)
        self.quests = QListWidget()
        quests_layout.addWidget(self.quests)
        sidebar.addWidget(quests_box, 1)
        columns.addLayout(sidebar, 1)
        outer.addLayout(columns, 1)
        row = QHBoxLayout()
        self.menu_button = QPushButton("Main Menu")
        self.save_button = QPushButton("Save Game")
        self.save_button.setObjectName("saveGameButton")
        row.addWidget(self.menu_button)
        row.addStretch()
        row.addWidget(self.save_button)
        outer.addLayout(row)

    def show_session(self, session: GameSession) -> None:
        # QPlainTextEdit never interprets HTML or script from a future AI service.
        transcript = "\n\n".join(f"{entry['speaker']}: {entry['text']}" for entry in session.history)
        self.history.setPlainText(transcript)
        self.history.verticalScrollBar().setValue(self.history.verticalScrollBar().maximum())
        self.character_name.setText(session.character_name)
        self.character_details.setText(session.character_description)
        self.location.setText(f"{session.location}\n{session.world.name}")
        self.inventory.clear()
        self.inventory.addItems(session.inventory)
        self.quests.clear()
        self.quests.addItems(session.quests)
        self.action.clear()
        self.action.setFocus()



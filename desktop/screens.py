def title(text: str, subtitle: str = "") -> tuple[QLabel, QLabel]:
    heading = QLabel(text)
    heading.setObjectName("screenTitle")
    detail = QLabel(subtitle)
    detail.setWordWrap(True)
    detail.setObjectName("screenSubtitle")
    return heading, detail


class SecretLineEdit(QLineEdit):
    """Masked input with a gray italic placeholder and normal typed text."""

    def __init__(self, placeholder: str, parent=None):
        super().__init__(parent)
        self.setEchoMode(QLineEdit.EchoMode.Password)
        self.setPlaceholderText(placeholder)
        palette = self.palette()
        palette.setColor(QPalette.ColorRole.PlaceholderText, QColor("#90979f"))
        self.setPalette(palette)
        self.textChanged.connect(self._update_font)
        self._update_font(self.text())

    def _update_font(self, text: str) -> None:
        font = QFont(self.font())
        font.setItalic(not bool(text))
        self.setFont(font)


